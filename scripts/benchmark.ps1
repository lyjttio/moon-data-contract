param(
  [int]$Runs = 5
)

$ErrorActionPreference = "Stop"
$repoRoot = Split-Path -Parent $PSScriptRoot
$outputPath = Join-Path $repoRoot "benchmarks/latest.md"

if ($Runs -lt 1) {
  throw "Runs must be at least 1."
}

Push-Location $repoRoot
try {
  $version = (& moon version --all | Out-String).Trim()
  $os = [System.Environment]::OSVersion.VersionString
  $cpu = if ($env:PROCESSOR_IDENTIFIER) { $env:PROCESSOR_IDENTIFIER } else { "unknown" }
  $target = if ($env:OS -eq "Windows_NT") { "wasm-gc" } else { "native" }
  $samples = @()
  $benchmarkOutput = ""

  for ($run = 1; $run -le $Runs; $run++) {
    $elapsed = Measure-Command {
      $benchmarkOutput = (& moon run --target $target cmd/main -- benchmark | Out-String)
    }
    if ($LASTEXITCODE -ne 0) {
      throw "Benchmark command failed on run $run."
    }
    $samples += [pscustomobject]@{
      Run = $run
      ElapsedMs = [math]::Round($elapsed.TotalMilliseconds, 3)
    }
  }

  $operationsMatch = [regex]::Match($benchmarkOutput, "Total operations: (\d+)")
  if (-not $operationsMatch.Success) {
    throw "Benchmark output did not contain Total operations."
  }
  $operations = [int]$operationsMatch.Groups[1].Value
  $elapsedMatch = [regex]::Match($benchmarkOutput, "Total elapsed \(us\): ([0-9.]+)")
  $coreElapsed = if ($elapsedMatch.Success) { $elapsedMatch.Groups[1].Value } else { "unknown" }

  $lines = [System.Collections.Generic.List[string]]::new()
  $lines.Add("# Reproducible Benchmark Evidence")
  $lines.Add("")
  $lines.Add("This file is generated by ``scripts/benchmark.ps1``. Values below are measured on the current machine; they are not performance guarantees.")
  $lines.Add("")
  $lines.Add("- Date: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss zzz")")
  $lines.Add("- OS: $os")
  $lines.Add("- CPU: $cpu")
  $lines.Add("- MoonBit target: $target")
  $lines.Add("- Workload operations per run: $operations")
  $lines.Add("- MoonBit core elapsed reported by CLI (us): $coreElapsed")
  $lines.Add("")
  $lines.Add("## CLI wall-clock samples")
  $lines.Add("")
  $lines.Add("| Run | Wall-clock (ms) | Operations |")
  $lines.Add("| ---: | ---: | ---: |")
  foreach ($sample in $samples) {
    $lines.Add("| $($sample.Run) | $($sample.ElapsedMs) | $operations |")
  }
  $lines.Add("")
  $lines.Add("## Toolchain")
  $lines.Add("")
  $lines.Add("``````text")
  $lines.Add($version)
  $lines.Add("``````")
  $lines.Add("")
  $lines.Add("## Command")
  $lines.Add("")
  $lines.Add("``````powershell")
  $lines.Add("moon run --target $target cmd/main -- benchmark")
  $lines.Add("``````")

  $lines | Set-Content -LiteralPath $outputPath -Encoding utf8
  Write-Output "Wrote $outputPath"
}
finally {
  Pop-Location
}
